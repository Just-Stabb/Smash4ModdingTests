def clean(text):
    return re.sub(r"\s+", " ", (text or "").replace("|", "/")).strip()


def rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.reader(f))


def hexid(text):
    text = (text or "").strip()
    if re.fullmatch(r"0x[0-9a-fA-F]+", text):
        return int(text, 16)
    return None


def write(name, header, sections):
    """sections: list of (filter lines, [(value, name, description)])"""
    path = os.path.join(OUT, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    count = 0
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("# Generated by tools/Sm4shCommand/make_tooltips.py - edits here are overwritten.\n")
        f.write("# Put your own tooltips in custom.txt (or use Edit Tooltip in the script editor).\n")
        for line in header:
            f.write("# %s\n" % line)
        for filters, entries in sections:
            f.write("\n[any]\n")
            for flt in filters:
                f.write("%s\n" % flt)
            for value, nm, desc in entries:
                key = value if isinstance(value, str) else "0x%08X" % value
                f.write("%s = %s%s\n" % (key, nm, (" | " + desc) if desc else ""))
                count += 1
    return count


def variables():
    merged = OrderedDict()   # id -> [names], [descriptions]

    def add(vid, nm, desc):
        names, descs = merged.setdefault(vid, ([], []))
        if nm and nm not in names:
            names.append(nm)
        if desc and desc not in descs:
            descs.append(desc)

    for r in rows(os.path.join(NOTES, "Variables.csv"))[2:]:
        vid = hexid(r[0] if r else "")
        if vid is None or len(r) < 3:
            continue
        nm, usage = clean(r[1]), clean(r[2])
        who = clean(r[4]) if len(r) > 4 else ""
        if not nm and not usage:
            continue
        add(vid, nm or "(unnamed)", ("Used in: " + usage if usage else "") + (" (documented by %s)" % who if who else ""))

    # fighter_param (category 3): names from Sammi Husky's sheet
    fp = rows(os.path.join(REF, "fighter_param_attributes.csv"))
    ids, names = fp[1], fp[2]
    for i in range(3, min(len(ids), len(names))):
        vid = hexid(ids[i])
        if vid is not None and clean(names[i]):
            add(vid, clean(names[i]), "fighter_param stat %d (per character; reference/fighter_param_attributes.csv)" % (vid & 0xFFFFFF))

    for r in rows(os.path.join(NOTES, "STrans_ID.csv"))[1:]:
        vid = hexid(r[0] if r else "")
        if vid is None:
            continue
        term, actions = clean(r[2]) if len(r) > 2 else "", clean(r[1])
        add(vid, "STrans " + (term or "?"), ("Actions: " + actions) if actions else "")

    for r in rows(os.path.join(NOTES, "STransGroup_ID.csv"))[1:]:
        vid = hexid(r[0] if r else "")
        if vid is None:
            continue
        add(vid, "STransGroup " + (clean(r[1]) or "?"), ("STrans IDs: " + clean(r[3])) if len(r) > 3 and clean(r[3]) else "")

    entries = []
    for vid, (names, descs) in merged.items():
        entries.append((vid, " / ".join(names), "\\n".join(descs)))
    return write("variables.txt",
                 ["Variable IDs 0xXYZZZZZZ: X = type (0 float, 1 int, 2 flag), Y = group (0 instance work,",
                  "1 status work, 2 fighter_param_common, 3 fighter_param, 5-8 special move params, E STrans,",
                  "F STransGroup / position variables). Source: MSC Note Sheet (reference/msc-note-sheet)."],
                 [(["[type variable]"], entries)])


