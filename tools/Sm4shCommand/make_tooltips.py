def aliases():
    os.makedirs(ALIAS_OUT, exist_ok=True)
    lines = ["# Variable aliases for the common position / hitstun / hitstop variables (tools/position_vars_cave.py,",
             "# docs/position-variables.md). Generated by make_tooltips.py: put your own in custom.txt.",
             "# Combat variables: TARGET_QUANTITY, TARGET = SELF, OPP (nearest opponent), LASTHIT (last fighter",
             "# hit), SLOT1-SLOT8; QUANTITY = " + ", ".join(COMBAT_QUANTITIES) + ".",
             ""]
    for name, vid, note in alias_lines():
        lines.append("%-22s = 0x%08X%s" % (name, vid, ("   # " + note) if note else ""))
    with open(os.path.join(ALIAS_OUT, "variables.txt"), "w", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(alias_lines())


def gfx():
    entries = []
    for r in rows(os.path.join(NOTES, "Global_GFX_IDs.csv"))[1:]:
        vid = hexid(r[0] if r else "")
        if vid is None or not clean(r[1]):
            continue
        entries.append((0x1000000 + vid, clean(r[1]), "Common effect %s (MSC Note Sheet, Global GFX IDs)" % r[0].strip()))
    return write("gfx.txt", ["Common effects: Graphic=0x1000000 + the global GFX list index."],
                 [(["[param Graphic]"], entries)])


