def articles():
    sections = []
    root = ET.parse(os.path.join(REF, "FighterArticles.xml")).getroot()
    for fighter in root.findall("Fighter"):
        name = fighter.get("Name")
        entries = [(a.get("ID"), a.get("Name"),
                    "Reserved slot: no article of its own in the game's table (Kirby's copy abilities use these)"
                    if a.get("Name") == "reserve" else
                    "%s article %s (max %s at a time)" % (a.get("Type"), a.get("ID"), a.get("Count")))
                   for a in fighter.findall("Article")]
        if entries:
            who = "[fighter %s]" % ", ".join([name] + ALIASES.get(name, []))
            sections.append(([who, "[param Article]"], entries))
            sections.append(([who, "[command %s]" % ", ".join(ARTICLE_COMMANDS), "[index 1]"], entries))
    return write("articles.txt", ["Article IDs per fighter (reference/FighterArticles.xml)."], sections)


def fighters():
    total = 0
    folder = os.path.join(REF, "fighter_param_vl")
    for f in sorted(os.listdir(folder)):
        tab = f[:-4]
        if tab not in FIGHTERS:
            continue
        name = FIGHTERS[tab]
        table = rows(os.path.join(folder, f))
        head = [h.strip().lower() for h in table[0]]
        idc = next(i for i, h in enumerate(head) if h.startswith("var"))
        descc = head.index("description")
        commc = head.index("comment") if "comment" in head else None
        valc = [i for i in range(idc + 1, descc)]
        move = ""
        entries = []
        for r in table[1:]:
            if len(r) <= descc:
                continue
            if clean(r[2]):
                move = clean(r[2])
            vid = hexid(r[idc])
            if vid is None:
                continue
            desc, comment = clean(r[descc]), clean(r[commc]) if commc is not None and len(r) > commc else ""
            values = ", ".join("%s %s" % (table[0][i].strip(), r[i].strip()) for i in valc if r[i].strip())
            info = "%s param %d" % (move or "Special", vid & 0xFFFFFF)
            parts = [info]
            if values:
                parts.append(values)
            if comment:
                parts.append(comment)
            entries.append((vid, desc or "(no description)", "\\n".join(parts)))
        if entries:
            total += write(os.path.join("fighters", name + ".txt"),
                           ["%s special move params (fighter_param_vl sheet, reference/fighter_param_vl/%s)." % (tab.replace("_", " "), f)],
                           [(["[fighter %s]" % ", ".join([name] + ALIASES.get(name, [])), "[type variable]"], entries)])
    return total


def main():
    counts = OrderedDict()
    counts["variables"] = variables()
    counts["position_variables"] = position()
    counts["aliases"] = aliases()
    counts["gfx"] = gfx()
    counts["angles"] = angles()
    counts["articles"] = articles()
    counts["fighters/*"] = fighters()
    for k, v in counts.items():
        print("%-20s %d" % (k, v))


if __name__ == "__main__":
    main()
